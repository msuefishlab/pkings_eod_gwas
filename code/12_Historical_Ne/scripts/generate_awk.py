#!/usr/bin/env python3
"""
generate_awk.py — generate an awk script for per-population call-rate filtering.

Usage:
    python3 generate_awk.py vcf_samples.txt samples_dir BAM BIK ... > compute_callrate.awk

The awk script reads: '%CHROM\t%POS[\t%GT]\n' output from bcftools query.
Called with: awk -f compute_callrate.awk -v outdir=DIR -v chrom_name=CHRN

Outputs: for each site with population call rate < 0.8, writes
  CHROM\t(POS-1)\tPOS  to  outdir/POP.chrom_name.lowcall.bed
"""

import sys
import os


def main():
    vcf_samples_file = sys.argv[1]
    samples_dir      = sys.argv[2]
    pops             = sys.argv[3:]

    # Read VCF sample order
    with open(vcf_samples_file) as fh:
        vcf_samples = [l.strip() for l in fh if l.strip()]
    # Map sample ID → 1-based awk column index (col 1 = CHROM, col 2 = POS, col 3+ = GT)
    sample_to_col = {s: i + 3 for i, s in enumerate(vcf_samples)}
    print(f"# Generated by generate_awk.py from {len(vcf_samples)} VCF samples",
          file=sys.stderr)

    # Collect per-population column lists
    pop_data = {}
    for pop in pops:
        samples_file = os.path.join(samples_dir, f'{pop}.txt')
        with open(samples_file) as fh:
            samples = [l.strip() for l in fh
                       if l.strip() and not l.startswith('#')]
        cols = [sample_to_col[s] for s in samples if s in sample_to_col]
        missing = [s for s in samples if s not in sample_to_col]
        if missing:
            print(f"# WARNING {pop}: {len(missing)} samples not in VCF: "
                  f"{missing[:3]}{'...' if len(missing)>3 else ''}",
                  file=sys.stderr)
        pop_data[pop] = cols
        print(f"# {pop}: {len(cols)} samples mapped ({len(samples)} in list)",
              file=sys.stderr)

    # ------- Generate awk script -------
    out = []
    out.append('BEGIN {')
    out.append('    thres = 0.8')
    for pop in pops:
        cols = pop_data[pop]
        n    = len(cols)
        # Build the split() string — space-separated column indices
        cols_str = ' '.join(map(str, cols))
        out.append(f'    split("{cols_str}", {pop}_cols)')
        out.append(f'    {pop}_n = {n}')
        out.append(f'    {pop}_out = outdir "/{pop}." chrom_name ".lowcall.bed"')
    out.append('}')
    out.append('{')
    out.append('    pos = $2 + 0')
    for pop in pops:
        n = len(pop_data[pop])
        out.append(f'    # {pop}')
        out.append(f'    nm_{pop} = 0')
        out.append(f'    for (i = 1; i <= {pop}_n; i++) {{')
        out.append(f'        if (substr(${pop}_cols[i], 1, 1) == ".") nm_{pop}++')
        out.append(f'    }}')
        out.append(f'    if ((({n} - nm_{pop}) / {n}) < thres)')
        out.append(f'        print $1 "\\t" (pos - 1) "\\t" pos >> {pop}_out')
    out.append('}')

    print('\n'.join(out))


if __name__ == '__main__':
    main()
